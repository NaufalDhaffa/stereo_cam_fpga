"""Turn the OV2640 register tables of esp32-camera into a Tcl file.

    python gen_tables.py <dir with ov2640_settings.h and ov2640_regs.h> ov2640_tables.tcl

The tables come from espressif/esp32-camera (Apache-2.0); the register names
in ov2640_regs.h come from the OpenMV project (MIT). Only the numeric
(register, value) pairs are emitted.
"""
import re
import sys
from pathlib import Path

TABLES = ["ov2640_settings_cif", "ov2640_settings_to_cif",
          "ov2640_settings_to_svga", "ov2640_settings_to_uxga",
          "ov2640_settings_yuv422", "ov2640_settings_rgb565"]


def load_macros(text):
    objs = {"BANK_DSP": "0", "BANK_SENSOR": "1"}
    funcs = {}
    for m in re.finditer(r"^#define\s+(\w+)(\([^)]*\))?\s+(.+?)\s*(?:/\*.*)?$", text, re.M):
        name, params, body = m.groups()
        if params:
            funcs[name] = ([p.strip() for p in params[1:-1].split(",")], body)
        else:
            objs[name] = body
    return objs, funcs


def evaluate(expr, objs, funcs):
    for _ in range(50):
        before = expr
        # innermost function-like macro calls first
        def call(m):
            name = m.group(1)
            if name not in funcs:
                return m.group(0)
            params, body = funcs[name]
            args = [a.strip() for a in m.group(2).split(",")]
            for p, a in zip(params, args):
                body = re.sub(rf"\b{p}\b", f"({a})", body)
            return f"({body})"
        expr = re.sub(r"\b(\w+)\(([^()]*)\)", call, expr)
        expr = re.sub(r"\b[A-Za-z_]\w*\b",
                      lambda m: f"({objs[m.group(0)]})" if m.group(0) in objs else m.group(0),
                      expr)
        if expr == before:
            break
    return int(eval(expr, {"__builtins__": {}})) & 0xFF


def split_pair(entry):
    depth = 0
    for i, ch in enumerate(entry):
        depth += ch == "("
        depth -= ch == ")"
        if ch == "," and depth == 0:
            return entry[:i].strip(), entry[i + 1:].strip().rstrip(",").strip()
    raise ValueError(entry)


def main():
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    objs, funcs = load_macros((src / "ov2640_regs.h").read_text())
    settings = (src / "ov2640_settings.h").read_text()
    lines = ["# OV2640 register tables, generated by gen_tables.py from",
             "# espressif/esp32-camera (Apache-2.0). Each list is reg value reg value ...",
             ""]
    for name in TABLES:
        body = re.search(name + r"\[\]\[2\]\s*=\s*\{(.*?)\n\};", settings, re.S).group(1)
        body = re.sub(r"//.*", "", body)
        pairs = [tuple(evaluate(x, objs, funcs) for x in split_pair(e))
                 for e in re.findall(r"\{([^{}]+)\}", body)]
        if pairs[-1] != (0, 0):
            raise SystemExit(f"{name}: missing terminator")
        pairs.pop()
        lines.append(f"set {name} {{")
        for i in range(0, len(pairs), 8):
            lines.append("    " + "  ".join(f"0x{r:02X} 0x{v:02X}" for r, v in pairs[i:i + 8]))
        lines.append("}")
        lines.append("")
        print(f"{name}: {len(pairs)} writes")
    out.write_text("\n".join(lines))


if __name__ == "__main__":
    main()

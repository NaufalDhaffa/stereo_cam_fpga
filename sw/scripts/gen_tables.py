"""ov2640_tables.h for the bare-metal application, from sensor/ov2640_tables.tcl.

    python sw/scripts/gen_tables.py
"""
import os
import re

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
USED = ("ov2640_settings_cif", "ov2640_settings_to_cif", "ov2640_settings_rgb565")


def main():
    text = open(os.path.join(ROOT, "sensor", "ov2640_tables.tcl")).read()
    out = ["/* OV2640 register tables: {register, value} pairs. Generated by sw/scripts/gen_tables.py",
           " * from sensor/ov2640_tables.tcl (after espressif/esp32-camera, Apache-2.0). */",
           "#ifndef OV2640_TABLES_H", "#define OV2640_TABLES_H", "", "#include \"xil_types.h\"", ""]
    for name, body in re.findall(r"set\s+(\w+)\s*\{([^}]*)\}", text):
        if name not in USED:
            continue
        v = [int(x, 0) for x in body.split()]
        out.append(f"static const u8 {name}[][2] = {{")
        pairs = [f"{{0x{r:02X}, 0x{d:02X}}}" for r, d in zip(v[0::2], v[1::2])]
        for i in range(0, len(pairs), 6):
            out.append("    " + ", ".join(pairs[i:i + 6]) + ",")
        out.append("};")
        out.append("")
    out.append("#endif")
    path = os.path.join(ROOT, "sw", "apps", "stereo_cam", "src", "ov2640_tables.h")
    open(path, "w", newline="\n").write("\n".join(out) + "\n")
    print(path)


if __name__ == "__main__":
    main()
